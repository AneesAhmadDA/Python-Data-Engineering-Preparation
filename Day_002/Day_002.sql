--Find the orders with an amount greater than 3000
Select * from orders where amount>3000;
--Total order amount for each customers 
Select c.customer_id,c.customer_name,COALESCE(SUM(o.amount),0) as total_amount from customers c
         LEFT JOIN orders o on c.customer_id=o.customer_id
         Group by c.customer_id,c.customer_name
         Order by COALESCE(SUM(o.amount),0) desc;

--join the customers and orders to display the customers names ith their orders
select c.customer_id,c.customer_name,c.city,o.order_id,o.amount from customers c 
    INNER JOIN orders o on c.customer_id=o.customer_id

--Find the total revenue generated by each city 

Select c.city,COALESCE(SUM(o.amount),0) as Revenue_generated from customers c
    left join orders o on c.customer_id=o.customer_id
    group by c.city
    order by COALESCE(SUM(o.amount),0) desc;
         